import {mkdir, readFile, readdir, rename, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {build} from "esbuild";

async function main() {
  const directory = path.dirname(fileURLToPath(import.meta.url));
  const outputDirectory = path.resolve(directory, process.argv[2] || "..");
  const worker = await build({
    absWorkingDir: directory,
    entryPoints: ["node_modules/monaco-editor/esm/vs/editor/editor.worker.js"],
    bundle: true,
    format: "iife",
    target: "es2018",
    minify: true,
    metafile: true,
    legalComments: "none",
    write: false,
  });
  const editor = await build({
    absWorkingDir: directory,
    entryPoints: ["editor.mjs"],
    outfile: "editor.mjs",
    bundle: true,
    format: "esm",
    target: "es2018",
    minify: true,
    metafile: true,
    legalComments: "none",
    write: false,
    loader: {".ttf": "dataurl"},
    plugins: [{
      name: "embedded-editor-worker",
      setup(builder) {
        builder.onResolve({filter: /^workspace-editor-worker$/}, () => ({
          path: "editor-worker", namespace: "embedded-worker",
        }));
        builder.onLoad({filter: /.*/, namespace: "embedded-worker"}, () => ({
          contents: worker.outputFiles[0].text, loader: "text",
        }));
      },
    }],
    banner: {js: "// Generated by workspace_server/frontend/build.mjs. See content_views.LICENSE.txt."},
  });
  const controller = await build({
    absWorkingDir: directory,
    entryPoints: ["content_views.mjs", "content_views.css"],
    outdir: ".",
    outExtension: {".js": ".mjs"},
    external: ["./editor.mjs"],
    supported: {"import-meta": true},
    bundle: true,
    format: "esm",
    target: "es2018",
    minify: true,
    metafile: true,
    legalComments: "none",
    write: false,
    banner: {js: "// Generated by workspace_server/frontend/build.mjs. See content_views.LICENSE.txt."},
  });
  const packages = new Set();
  for (const input of Object.keys({
    ...worker.metafile.inputs, ...editor.metafile.inputs, ...controller.metafile.inputs,
  })) {
    if (!input.startsWith("node_modules/")) continue;
    const parts = input.split("/");
    packages.add(parts[1].startsWith("@") ? parts.slice(1, 3).join("/") : parts[1]);
  }
  const licenses = [];
  for (const name of Array.from(packages).sort()) {
    const packageRoot = path.join(directory, "node_modules", name);
    const metadata = JSON.parse(await readFile(path.join(packageRoot, "package.json"), "utf8"));
    const files = await readdir(packageRoot);
    const licenseName = files.find(file => /^licen[cs]e(?:\.(md|txt))?$/i.test(file));
    const license = await readFile(path.join(packageRoot, licenseName), "utf8");
    const notices = files.filter(file => /^thirdpartynotices\./i.test(file));
    const texts = [license];
    for (const file of notices) texts.push(await readFile(path.join(packageRoot, file), "utf8"));
    licenses.push(`${name} ${metadata.version}\n${texts.map(text => text.trim()).join("\n\n")}`);
  }
  await mkdir(outputDirectory, {recursive: true});
  const outputs = [
    ["content_views.LICENSE.txt", licenses.join("\n\n") + "\n"],
    ...editor.outputFiles.map(file => [path.basename(file.path), file.contents]),
    ["content_views.css", controller.outputFiles.find(file => file.path.endsWith(".css")).contents],
    ["content_views.mjs", controller.outputFiles.find(file => file.path.endsWith(".mjs")).contents],
  ];
  for (const [name, contents] of outputs) {
    await writeFile(path.join(outputDirectory, name) + ".tmp", contents);
  }
  for (const [name] of outputs) {
    const target = path.join(outputDirectory, name);
    await rename(target + ".tmp", target);
  }
  console.log(`Built content views and editor assets with licenses for ${packages.size} packages in ${outputDirectory}.`);
}

await main();
